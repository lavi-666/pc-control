  const cardEn = document.getElementById('langOptEn');

  if (checkUa) checkUa.innerText = (currentLang === 'uk') ? '✓' : '';
  if (checkRu) checkRu.innerText = (currentLang === 'ru') ? '✓' : '';
  if (checkEn) checkEn.innerText = (currentLang === 'en') ? '✓' : '';

